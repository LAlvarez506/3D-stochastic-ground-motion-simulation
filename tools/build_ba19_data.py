"""
Regenerate ``stochastic_gm/ba19_data.py`` (developer tool, not needed to use the package).

Inputs
------
* the correlation matrices of Bayless & Abrahamson (2019) as a pickle with keys
  ``freqs``, ``Total``, ``W`` and ``within-site`` (``W`` was identified as the
  BETWEEN-SITE matrix by comparison with Fig. 5b of the paper);
* ``Bayless_ModelCoefs.xlsx`` from the electronic supplement (columns s1-s6 and
  c1a: standard deviations of the BA18 EAS model).

Usage
-----
    python tools/build_ba19_data.py correlations.pkl Bayless_ModelCoefs.xlsx

Only load a pickle you trust (pickle can execute code).
"""
import pickle
import sys
from pathlib import Path

import numpy as np

SCALE = 100000          # matrices are stored as integers of 1e-5
N_FREQ = 239


def main(pkl_path, xlsx_path, out_path=None):
    import openpyxl
    out_path = Path(out_path or Path(__file__).resolve().parents[1]
                    / 'stochastic_gm' / 'ba19_data.py')

    d = pickle.load(open(pkl_path, 'rb'))
    ws = openpyxl.load_workbook(xlsx_path, data_only=True).active
    rows = list(ws.iter_rows(values_only=True))
    head, body = rows[0], rows[1:1 + N_FREQ]
    col = lambda name: np.array([r[head.index(name)] for r in body], float)

    freqs = col('f (Hz)')
    if np.abs(freqs - d['freqs']).max() > 1e-3:
        raise ValueError("frequency grids of pickle and workbook differ")
    sig = {k: col(k) for k in ('s1', 's2', 's3', 's4', 's5', 's6', 'c1a')}

    mats = {'total': d['Total'], 'within_site': d['within-site'], 'between_site': d['W']}
    iu = np.tril_indices(N_FREQ)
    lines = ['"""',
             'Data of Bayless & Abrahamson (2019, BSSA 109(3), doi:10.1785/0120180238)',
             'and of the BA18 EAS model (PEER report 2018/07), generated by',
             'tools/build_ba19_data.py.  Do not edit by hand.',
             '',
             'FREQS        : 239 model frequencies [Hz], 0.1-23.99',
             'LOWER_TRI    : correlation matrices, lower triangle (row by row, diagonal',
             '               included) as integers of 1e-5.  Keys: total (smooth BA19 model),',
             '               within_site, between_site (empirical).',
             'SIGMA        : s1..s6 and c1a of the BA18 model (ln units):',
             '               tau = s1 (M<=4) .. s2 (M>=6); phi_s2s = s3 .. s4;',
             '               phi_ss = s5 .. s6; linear in M between 4 and 6;',
             '               sigma_total^2 = tau^2 + phi_s2s^2 + phi_ss^2 + c1a^2.',
             '"""', '']
    lines.append('SCALE = %d' % SCALE)
    lines.append('FREQS = (' + ', '.join(repr(float(x)) for x in freqs) + ')')
    lines.append('SIGMA = {')
    for k, v in sig.items():
        lines.append('    %r: (%s),' % (k, ', '.join(repr(float(x)) for x in v)))
    lines.append('}')
    lines.append('LOWER_TRI = {')
    for name, M in mats.items():
        M = np.asarray(M, float)
        if not np.allclose(M, M.T, atol=1e-9):
            raise ValueError(f"{name} is not symmetric")
        q = np.rint(M[iu] * SCALE).astype(int)
        back = np.zeros_like(M)
        back[iu] = q / SCALE
        back = back + back.T - np.diag(np.diag(back))
        print(f"{name:13s} max rounding error {np.abs(back - M).max():.1e}, "
              f"min eig {np.linalg.eigvalsh(back).min():.2e}")
        lines.append('    %r: (%s),' % (name, ', '.join(str(int(x)) for x in q)))
    lines.append('}')
    out_path.write_text('\n'.join(lines) + '\n')
    print('written', out_path, out_path.stat().st_size // 1024, 'kB')


if __name__ == '__main__':
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    main(*sys.argv[1:4])
